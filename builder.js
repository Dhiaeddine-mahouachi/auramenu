  function blobToDataUrl(blob) {
    return new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.addEventListener("load", () => resolve(String(reader.result || "")));
      reader.addEventListener("error", () => reject(reader.error));
      reader.readAsDataURL(blob);
    });
  }
  async function loadPhoto(file) {
    if ("createImageBitmap" in window) {
      try {
        const bitmap = await createImageBitmap(file, {
          imageOrientation: "from-image",
        });
        return {
          source: bitmap,
          width: bitmap.width,
          height: bitmap.height,
          close: () => bitmap.close(),
        };
      } catch {}
    }
    const objectUrl = URL.createObjectURL(file);
    const image = new Image();
    image.decoding = "async";
    image.src = objectUrl;
    await image.decode();
    return {
      source: image,
      width: image.naturalWidth,
      height: image.naturalHeight,
      close: () => URL.revokeObjectURL(objectUrl),
    };
  }
  async function compressPhoto(file) {
    if (!PHOTO_TYPES.has(file.type)) throw new Error(i18n[lang].invalidPhoto);
    if (file.size > MAX_SOURCE_PHOTO_BYTES)
      throw new Error(i18n[lang].sourceTooLarge);
    const photo = await loadPhoto(file);
    try {
      if (!photo.width || !photo.height) throw new Error(i18n[lang].invalidPhoto);
      let scale = Math.min(1, 960 / Math.max(photo.width, photo.height));
      let quality = 0.82;
      for (let attempt = 0; attempt < 8; attempt += 1) {
        const canvas = document.createElement("canvas");
        canvas.width = Math.max(1, Math.round(photo.width * scale));
        canvas.height = Math.max(1, Math.round(photo.height * scale));
        const context = canvas.getContext("2d", { alpha: true });
        if (!context) throw new Error(i18n[lang].photoTooLarge);
        context.drawImage(photo.source, 0, 0, canvas.width, canvas.height);
        const blob = await canvasToBlob(canvas, "image/webp", quality);
        if (
          blob &&
          PHOTO_TYPES.has(blob.type) &&
          blob.size <= MAX_PHOTO_BYTES
        ) {
          return blobToDataUrl(blob);
        }
        quality = Math.max(0.5, quality - 0.08);
        if (attempt >= 3) scale *= 0.84;
      }
      throw new Error(i18n[lang].photoTooLarge);
    } finally {
      photo.close();
    }
  }
